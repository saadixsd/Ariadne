// Compiles agents/playbooks/*.md into lib/playbooks.generated.ts (no runtime file reads).
// Run: node scripts/build-playbooks.mjs   (tests/unit/playbooks.test.ts fails if it is stale)
import fs from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "agents/playbooks");
const ORDER = ["researcher", "brief-analysis", "research", "answer-writing", "revision", "fact-check"];
const books = ORDER.map((name) => {
  const raw = fs.readFileSync(path.join(dir, `${name}.md`), "utf8").replace(/\r\n?/g, "\n");
  const m = raw.match(/^---\n([\s\S]*?)\n---\n/);
  const meta = Object.fromEntries((m?.[1] ?? "").split("\n").map((l) => l.split(/:\s*/, 2)));
  return { name, version: Number(meta.version), for: String(meta.for).split(/,\s*/), body: raw.slice(m ? m[0].length : 0).trim() };
});
const compose = (who) => books.filter((b) => b.for.includes(who)).map((b) => b.body).join("\n\n");
const versions = books.map((b) => `${b.name}@${b.version}`).join(" ");
export const generated = `// Generated by scripts/build-playbooks.mjs from agents/playbooks/*.md. Do not edit.
export const PLAYBOOK_VERSIONS = ${JSON.stringify(versions)};
export const WRITER_PLAYBOOK = ${JSON.stringify(compose("writer"))};
export const CHECKER_PLAYBOOK = ${JSON.stringify(compose("checker"))};
`;
if (process.argv[1]?.endsWith("build-playbooks.mjs")) {
  fs.writeFileSync(path.join(process.cwd(), "lib/playbooks.generated.ts"), generated);
  console.log("playbooks:", versions);
}
